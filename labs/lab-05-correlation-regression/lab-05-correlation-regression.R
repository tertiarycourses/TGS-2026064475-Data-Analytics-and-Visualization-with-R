args <- commandArgs(trailingOnly = FALSE)
file_arg <- grep("^--file=", args, value = TRUE)
lab_dir <- if (length(file_arg)) dirname(normalizePath(sub("^--file=", "", file_arg[1]))) else normalizePath(getwd())
data_path <- function(name) file.path(lab_dir, "data", name)
out_path <- function(name) file.path(lab_dir, "outputs", name)
dir.create(out_path(""), recursive = TRUE, showWarnings = FALSE)
options(stringsAsFactors = FALSE)

h <- read.csv(data_path("health-research.csv"))
ct <- cor.test(h$cancer_cell,h$weight,method="pearson")
m <- lm(weight~cancer_cell,h)
sm <- summary(m)
cor_out <- data.frame(correlation=unname(ct$estimate),p_value=ct$p.value,conf_low=ct$conf.int[1],conf_high=ct$conf.int[2])
model_out <- data.frame(term=rownames(coef(sm)),estimate=coef(sm)[,"Estimate"],std_error=coef(sm)[,"Std. Error"],t_value=coef(sm)[,"t value"],p_value=coef(sm)[,"Pr(>|t|)"],row.names=NULL)
model_out$r_squared <- c(sm$r.squared,rep(NA,nrow(model_out)-1))
pred <- predict(m,newdata=data.frame(cancer_cell=c(10,25,40)),interval="prediction")
write.csv(cor_out,out_path("lab-05-correlation.csv"),row.names=FALSE); write.csv(model_out,out_path("lab-05-model-summary.csv"),row.names=FALSE); write.csv(data.frame(cancer_cell=c(10,25,40),pred),out_path("lab-05-prediction.csv"),row.names=FALSE)
png(out_path("lab-05-model-diagnostics.png"),1200,650,res=130); par(mfrow=c(1,2)); plot(h$cancer_cell,h$weight,pch=19,col="#1F6FEB",xlab="Cancer-cell indicator",ylab="Weight (kg)",main="Observed relationship"); abline(m,col="#DC2626",lwd=2); plot(fitted(m),residuals(m),pch=19,col="#10B981",xlab="Fitted",ylab="Residual",main="Residuals versus fitted"); abline(h=0,lty=2); dev.off()
cat("Lab 5 complete; R-squared", round(sm$r.squared,3), "\n")
