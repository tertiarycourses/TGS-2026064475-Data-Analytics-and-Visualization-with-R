args <- commandArgs(trailingOnly = FALSE)
file_arg <- grep("^--file=", args, value = TRUE)
lab_dir <- if (length(file_arg)) dirname(normalizePath(sub("^--file=", "", file_arg[1]))) else normalizePath(getwd())
data_path <- function(name) file.path(lab_dir, "data", name)
out_path <- function(name) file.path(lab_dir, "outputs", name)
dir.create(out_path(""), recursive = TRUE, showWarnings = FALSE)
options(stringsAsFactors = FALSE)

v <- read.csv(data_path("vaccination.csv"), check.names=FALSE)
c <- read.csv(data_path("clinic-reference.csv"), check.names=FALSE)
standardise_key <- function(x) tolower(trimws(x))
v$key <- standardise_key(v$vaccination_type); c$key <- standardise_key(c$vaccination_type)
stopifnot(!anyDuplicated(c$key))
j <- merge(v, c[c("key","vaccine_group","clinic_owner")], by="key", all.x=TRUE, sort=FALSE)
unmatched <- unique(j[is.na(j$vaccine_group), c("vaccination_type"), drop=FALSE])
annual <- aggregate(no_of_doses_in_thousands ~ year + vaccine_group, j, sum, na.rm=TRUE)
wide <- reshape(annual, idvar="year", timevar="vaccine_group", direction="wide")
write.csv(j, out_path("lab-02-joined-long.csv"), row.names=FALSE)
write.csv(unmatched, out_path("lab-02-unmatched-keys.csv"), row.names=FALSE)
write.csv(annual, out_path("lab-02-annual-summary.csv"), row.names=FALSE)
write.csv(wide, out_path("lab-02-wide-summary.csv"), row.names=FALSE)
audit <- data.frame(control=c("Input rows", "Joined rows", "Input doses", "Summary doses", "Unmatched keys"), value=c(nrow(v), nrow(j), sum(v$no_of_doses_in_thousands,na.rm=TRUE), sum(annual$no_of_doses_in_thousands,na.rm=TRUE), nrow(unmatched)))
write.csv(audit, out_path("lab-02-audit.csv"), row.names=FALSE)
stopifnot(nrow(v)==nrow(j), abs(sum(v$no_of_doses_in_thousands,na.rm=TRUE)-sum(annual$no_of_doses_in_thousands,na.rm=TRUE))<1e-8)
cat("Lab 2 complete; unmatched keys:", nrow(unmatched), "\n")
